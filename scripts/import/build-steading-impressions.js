// Lift each steading article's per-season IMPRESSIONS into its steadfast's `system.impressions`.
//
//   node scripts/import/build-steading-impressions.js
//
// Book II's village articles print, under "Impressions", a few sensory lines for each season — the
// book's own words for what the place is like right now. The Season tab quotes one when the wheel
// turns, which means it must come from the book: a sentence about Stonetop in autumn is exactly the
// kind of thing that must never be written by us.
//
// A pass over the pack SOURCES, like build-seasonal-clauses.js beside it, and for the same reason:
// the article is generated by build-journal, and the steadfast it writes into is hand-authored. It
// runs after both, and is idempotent.
//
// packs/src/steadfasts/stonetop.json is hand-authored and build-steadfasts.js protects it by name
// (its KEEP set), so nothing else in the build will overwrite what this writes.
import { readFileSync, readdirSync, writeFileSync } from "fs";
import path from "path";
import { pathToFileURL } from "node:url";
import { articleHtml, impressionsFrom } from "./steadingImpressions.js";
import { Seasons } from "../../src/model/data/steading/Seasons.js";

const ARTICLES  = "packs/src/wider-world-and-other-wonders";
const STEADFASTS = "packs/src/steadfasts";
const REVIEW    = "helper/steading-impressions-review.md";

// Which article describes which steadfast. Named rather than matched by title, because "The village
// of Stonetop" and "stonetop" only look alike: a fuzzy match here would silently attach one
// village's weather to another's steadfast the first time two articles shared a word.
const ARTICLE_FOR = {
	"stonetop.json": "the-village-of-stonetop.json",
};

const trim = (text, max = 96) => (text.length > max ? `${text.slice(0, max - 1)}…` : text);

export function buildSteadingImpressions({ write = true } = {}) {
	const rows = [], flags = [];
	let changed = 0, total = 0;

	for (const steadfastFile of readdirSync(STEADFASTS).filter(f => f.endsWith(".json")).sort()) {
		const articleFile = ARTICLE_FOR[steadfastFile];
		if (!articleFile) continue;

		const articlePath = path.join(ARTICLES, articleFile);
		let article;
		try {
			article = JSON.parse(readFileSync(articlePath, "utf8"));
		} catch {
			flags.push(`! ${steadfastFile}: no article at ${articlePath} — impressions left as they were`);
			continue;
		}

		const impressions = impressionsFrom(articleHtml(article));
		if (!impressions.length) {
			flags.push(`! ${articleFile}: no Impressions section found — check the article's headings`);
		}
		for (const season of Seasons.all()) {
			if (!impressions.some(i => i.season === season.key)) {
				flags.push(`? ${articleFile}: nothing for ${season.key}`);
			}
		}

		const steadfastPath = path.join(STEADFASTS, steadfastFile);
		const raw = readFileSync(steadfastPath, "utf8");
		const doc = JSON.parse(raw);
		doc.system ??= {};
		// Written even when empty, so an article that stops printing the section clears the steadfast
		// rather than leaving last build's lines behind forever.
		doc.system.impressions = impressions;

		// Tabs: packs/src/steadfasts is tab-indented (build-steadfasts.js writes it that way), unlike
		// the improvements pack. Matching it keeps the diff to the lines that actually changed.
		const next = `${JSON.stringify(doc, null, "\t")}\n`;
		if (next !== raw) { changed++; if (write) writeFileSync(steadfastPath, next); }

		total += impressions.length;
		rows.push(`### ${doc.name ?? steadfastFile}\n\n` + Seasons.all().map(season => {
			const lines = impressions.filter(i => i.season === season.key);
			return `- **${season.key}** (${lines.length})\n` +
				lines.map(l => `  - ${trim(l.text)}`).join("\n");
		}).join("\n"));
	}

	const review = `# Steading impressions — generated ${new Date().toISOString().slice(0, 10)}\n\n` +
		`${total} line(s) lifted into \`system.impressions\` on the steadfasts below, by\n` +
		`scripts/import/build-steading-impressions.js.\n\n` +
		`These are the book's own sensory lines for each season, taken from the FIRST list under each\n` +
		`season heading in the article's "Impressions" section. The Activities and Questions lists below\n` +
		`them are a different thing — chores and table prompts, not a description of the place — and are\n` +
		`deliberately left alone. The Season tab quotes one of these when the wheel turns.\n\n` +
		`${rows.length ? rows.join("\n\n") : "_none_"}\n` +
		(flags.length ? `\n## Needs attention\n\n${flags.map(f => `- ${f}`).join("\n")}\n` : "");
	if (write) writeFileSync(REVIEW, review);

	return { total, changed, flags };
}

function main() {
	const { total, changed, flags } = buildSteadingImpressions();
	console.log(`steading impressions: ${total} line(s); ${changed} steadfast(s) rewritten; review → ${REVIEW}`);
	if (flags.length) {
		console.error(`\n${flags.length} note(s):\n${flags.join("\n")}`);
		process.exitCode = 1;
	}
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	main();
}
